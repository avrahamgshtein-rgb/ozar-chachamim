#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Builds nextjs-app/public/data-youtube.json: the video of each sage, per language, from the
site owner's YouTube playlist of sage videos (English, Russian and a few Hebrew).

    python3 scripts/build_youtube_links.py            # offline: just writes the file
    python3 scripts/build_youtube_links.py --check    # also asks YouTube's oEmbed whether each
                                                      # chosen video can be embedded, and drops
                                                      # the ones that cannot

Inputs, both in data/:
  youtube-playlist.tsv    a snapshot of the playlist: row, video id, seconds, language, title
                          (taken with `yt-dlp --flat-playlist`; refresh it when videos are added)
  youtube-sage-map.json   which rows belong to which sage id. It is written by hand: the titles
                          are English / Russian / Hebrew renderings of a name and the roster's
                          labels are Hebrew, so a script cannot join them safely. Never renumber.

A sage can have several videos in one language (a lesson uploaded twice, or two takes of it): all of
them are kept, in playlist order, and the page shows the first and tucks the rest under "more videos".
The output carries the roster label each entry was made for, and tests/youtube.test.ts fails when
an id now belongs to another sage, like the Sefaria and Wikipedia files.
"""
import argparse, json, os, re, subprocess, sys, time, urllib.parse

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PLAYLIST = os.path.join(REPO, 'data', 'youtube-playlist.tsv')
MAP = os.path.join(REPO, 'data', 'youtube-sage-map.json')
ROSTER = os.path.join(REPO, 'nextjs-app', 'public', 'data.json')
OUT = os.path.join(REPO, 'nextjs-app', 'public', 'data-youtube.json')
PLAYLIST_ID = 'PLZTqkkizXfX-8NLT5G77GBhgMylisckyf'

ap = argparse.ArgumentParser()
ap.add_argument('--check', action='store_true', help='drop videos YouTube will not embed')
ap.add_argument('--pause', type=float, default=0.4, help='seconds between oEmbed requests')
args = ap.parse_args()


def oembed_status(video_id):
    url = 'https://youtube.com/oembed?format=json&url=' + urllib.parse.quote('https://youtu.be/' + video_id, safe='')
    r = subprocess.run(['curl', '-s', '-m', '20', '-o', '/dev/null', '-w', '%{http_code}', url], capture_output=True, text=True)
    return r.stdout.strip()


def main():
    rows = {}
    for line in open(PLAYLIST, encoding='utf-8'):
        n, vid, sec, lang, title = line.rstrip('\n').split('\t')
        rows[int(n)] = {'id': vid, 'seconds': int(sec or 0), 'lang': lang, 'title': title}
    mapping = json.load(open(MAP, encoding='utf-8'))['sages']
    labels = {n['id']: n['label'] for n in json.load(open(ROSTER, encoding='utf-8'))['nodes']}

    out, dropped, status_cache = {}, [], {}
    for sid in sorted(mapping, key=int):
        if sid not in labels:
            sys.exit('sage %s is not on the roster' % sid)
        entry = {'label': labels[sid]}
        for n in mapping[sid]:
            v = rows[n]
            if any(x['id'] == v['id'] for x in entry.get(v['lang'], [])):
                continue
            if args.check:
                if v['id'] not in status_cache:
                    time.sleep(args.pause)
                    status_cache[v['id']] = oembed_status(v['id'])
                if status_cache[v['id']] != '200':
                    dropped.append((sid, n, v['id'], status_cache[v['id']], v['title'][:60]))
                    continue
            entry.setdefault(v['lang'], []).append({'id': v['id'], 'title': v['title'], 'seconds': v['seconds']})
        if len(entry) > 1:
            out[sid] = entry

    doc = {
        '_about': 'Generated by scripts/build_youtube_links.py from data/youtube-playlist.tsv and data/youtube-sage-map.json. '
                  'Keys are sage ids; he/en/ru are the YouTube videos of that sage in that language, in playlist order.',
        'playlist': PLAYLIST_ID,
        'sages': out,
    }
    with open(OUT, 'w', encoding='utf-8') as f:
        json.dump(doc, f, ensure_ascii=False, indent=1)
        f.write('\n')
    per = {k: sum(1 for e in out.values() if k in e) for k in ('he', 'en', 'ru')}
    total = sum(len(e.get(k, [])) for e in out.values() for k in ('he', 'en', 'ru'))
    print('sages with a video: %d | he %d, en %d, ru %d | %d videos in all' % (len(out), per['he'], per['en'], per['ru'], total))
    if args.check:
        print('checked %d videos, dropped %d' % (len(status_cache), len(dropped)))
        for d in dropped:
            print('  dropped sage %s row %s %s HTTP %s %s' % d)


main()
