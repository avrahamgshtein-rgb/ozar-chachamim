/** A canonical place's name in the reader's language (Hebrew when unknown). */
export function placeName(place: string, locale: Locale): string {
  if (locale === 'he') return place
  const n = NAMES[place]
  if (!n) return place
  return locale === 'en' ? n[0] : n[1]
}
